export function explainResponse(line: string): string | null {
  const e = /^error:(\d+)/i.exec(line);
  if (e) return `Ошибка ${e[1]}: ${GRBL_ERRORS[+e[1]] ?? 'неизвестная ошибка.'}`;
  const a = /^ALARM:(\d+)/i.exec(line);
  if (a) return `Тревога ${a[1]}: ${GRBL_ALARMS[+a[1]] ?? 'неизвестная тревога.'}`;
  return null;
}

export interface GrblStatus {
  state: string;          // Idle, Run, Hold:0, Alarm, Door, Check, Home, Sleep, Jog
  mpos?: [number, number, number];
  wpos?: [number, number, number];
  feed?: number;
  overrides?: [number, number, number];
}

/** Разбор отчёта «<Idle|MPos:0.000,0.000,0.000|FS:0,0|WCO:...>». */
export function parseStatus(line: string, prevWco?: [number, number, number]): (GrblStatus & { wco?: [number, number, number] }) | null {
  const m = /^<([^>]+)>$/.exec(line.trim());
  if (!m) return null;
  const parts = m[1].split('|');
  const st: GrblStatus & { wco?: [number, number, number] } = { state: parts[0] };
  const nums = (s: string) => s.split(',').map(Number) as [number, number, number];
  for (const p of parts.slice(1)) {
    const [k, v] = p.split(':');
    if (!v) continue;
    if (k === 'MPos') st.mpos = nums(v);
    else if (k === 'WPos') st.wpos = nums(v);
    else if (k === 'WCO') st.wco = nums(v);
    else if (k === 'FS' || k === 'F') st.feed = Number(v.split(',')[0]);
    else if (k === 'Ov') st.overrides = nums(v);
  }
  const wco = st.wco ?? prevWco;
  if (!st.wpos && st.mpos && wco) st.wpos = [st.mpos[0] - wco[0], st.mpos[1] - wco[1], st.mpos[2] - wco[2]];
  if (!st.wpos && st.mpos && !wco) st.wpos = st.mpos;
  return st;
}

